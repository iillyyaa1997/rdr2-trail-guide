#!/usr/bin/env python3
"""Generate src/sdk/natives.gen.h from the open RDR3 native database (alloc8or/rdr3-nativedb-data).

The header declares every native as an inline function inside its namespace (PED::CREATE_PED, ...) that calls
tg::invoke<Ret>(hash, args...). Only names, hashes and parameter types are taken from the database.

usage: tools/gen_natives.py [--json .cache/natives.json] [--rev <commit sha>] [--out src/sdk/natives.gen.h]
"""
import argparse
import json
import keyword
import re
import sys

CPP_RESERVED = {
    # C++ keywords that can appear as parameter names in the database
    "alignas", "alignof", "and", "asm", "auto", "bool", "break", "case", "catch", "char", "class", "const", "constexpr",
    "continue", "default", "delete", "do", "double", "else", "enum", "explicit", "export", "extern", "false", "float",
    "for", "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "nullptr",
    "operator", "or", "private", "protected", "public", "register", "return", "short", "signed", "sizeof", "static",
    "struct", "switch", "template", "this", "throw", "true", "try", "typedef", "typeid", "typename", "union",
    "unsigned", "using", "virtual", "void", "volatile", "while", "xor",
    # windows.h macros that break identifiers (near/far bit us three times in the old mod)
    "near", "far", "min", "max", "IN", "OUT", "OPTIONAL", "interface", "small", "hyper", "pascal", "cdecl", "CALLBACK",
    "TRUE", "FALSE", "NULL", "BOOL", "DWORD", "WORD", "BYTE", "Hash", "Ped", "Entity", "Vector3", "Any", "Player",
}

PRIMITIVE = {"void", "int", "float", "BOOL", "Hash", "Any", "char", "Vector3"}


def ident(name: str, used: set, index: int) -> str:
    n = re.sub(r"[^A-Za-z0-9_]", "_", name or "")
    if not n or n[0].isdigit() or n in CPP_RESERVED or keyword.iskeyword(n) or n in used:
        n = f"p{index}"
        while n in used:
            n += "_"
    used.add(n)
    return n


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=".cache/natives.json")
    ap.add_argument("--rev", default="unknown")
    ap.add_argument("--out", default="src/sdk/natives.gen.h")
    a = ap.parse_args()

    db = json.load(open(a.json, encoding="utf-8"))
    handle_types = set()
    for ns in db.values():
        for f in ns.values():
            for t in [f.get("return_type", "void")] + [p["type"] for p in f.get("params", [])]:
                base = t.replace("const ", "").replace("*", "").strip()
                if base and base not in PRIMITIVE:
                    handle_types.add(base)

    out = []
    w = out.append
    w("// Generated by tools/gen_natives.py from github.com/alloc8or/rdr3-nativedb-data @ %s. Do not edit." % a.rev)
    w("// Every native calls tg::invoke<Ret>(hash, args...) (src/sdk/invoker.h).")
    w("#pragma once")
    w('#include "invoker.h"')
    w("")
    w("// handle types used by the database (script handles are 32-bit ints)")
    for t in sorted(handle_types):
        w(f"using {t} = int;")
    w("")
    total = 0
    for ns_name in sorted(db):
        ns = db[ns_name]
        w(f"namespace {ns_name} {{")
        seen = set()
        for h, f in sorted(ns.items(), key=lambda kv: kv[1].get("name", kv[0])):
            name = f.get("name") or ("_" + h)
            if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", name) or name in seen:
                w(f"// skipped {h} {name!r} (invalid or duplicate name)")
                continue
            seen.add(name)
            raw = f.get("params", [])
            variadic = any(p.get("name") == "..." or not p.get("type") for p in raw)
            raw = [p for p in raw if p.get("name") != "..." and p.get("type")]
            ret = f.get("return_type", "void")
            used = set()
            params = [(p["type"], ident(p.get("name"), used, i)) for i, p in enumerate(raw)]
            sig = ", ".join(f"{t} {n}" for t, n in params)
            args = "".join(f", {n}" for _, n in params)
            tmpl = ""
            if variadic:  # e.g. VAR_STRING(flags, "LITERAL_STRING", text): extra arguments pushed as they are
                tmpl = "template <typename... Va> "
                sig = (sig + ", " if sig else "") + "Va... va"
                args += ", va..."
            body = f"tg::invoke<{ret}>({h}ULL{args})"
            if ret == "void":
                w(f"{tmpl}inline void {name}({sig}) {{ {body}; }}")
            else:
                w(f"{tmpl}inline {ret} {name}({sig}) {{ return {body}; }}")
            total += 1
        w(f"}} // namespace {ns_name}")
        w("")
    w(f"// {total} natives")
    open(a.out, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(f"{a.out}: {total} natives, {len(handle_types)} handle types", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
